// MARK: - Park enums

enum UniversalPark: String, CaseIterable, Identifiable {
    case epicUniverse  = "Epic Universe"
    case studiosOrIOA  = "Studios / Islands of Adventure"
    case parkToPark    = "Park to Park (2 Parks)"
    case volcanoBay    = "Volcano Bay"
    var id: String { rawValue }
}

enum DisneyPark: String, CaseIterable, Identifiable {
    case magicKingdom    = "Magic Kingdom"
    case epcot           = "EPCOT"
    case hollywoodStudios = "Hollywood Studios"
    case animalKingdom   = "Animal Kingdom"
    case parkHopper      = "Park Hopper"
    case parkHopperPlus  = "Park Hopper Plus"
    var id: String { rawValue }
}

// MARK: - Service

struct TicketPriceService {

    // MARK: - Disney exact lookup

    static func disneyPrice(for date: Date, park: DisneyPark) -> Double? {
        let key = dateKey(from: date)
        guard let row = disneyPrices[key] else { return nil }
        switch park {
        case .magicKingdom:     return row.0
        case .epcot:            return row.1
        case .hollywoodStudios:  return row.2
        case .animalKingdom:    return row.3
        case .parkHopper:       return row.4
        case .parkHopperPlus:   return row.5
        }
    }

    // MARK: - Universal exact lookup (falls back to estimate for out-of-table dates)

    static func universalPrice(for date: Date, park: UniversalPark) -> Double? {
        let key = dateKey(from: date)
        guard let row = universalPrices[key] else { return nil }
        switch park {
        case .epicUniverse: return row.0
        case .studiosOrIOA: return row.1
        case .parkToPark:   return row.2
        case .volcanoBay:   return row.3
        }
    }

    static func universalEstimate(for date: Date) -> Double {
        let cal = Calendar.current
        let month   = cal.component(.month,   from: date)
        let day     = cal.component(.day,     from: date)
        let weekday = cal.component(.weekday, from: date)
        let isWeekend = weekday == 1 || weekday == 7
        switch month {
        case 1:  return day <= 6 ? 134 : (isWeekend ? 119 : 109)
        case 2:  return (day >= 14 && day <= 23) ? 134 : (isWeekend ? 119 : 109)
        case 3:  return isWeekend ? 139 : 134
        case 4:  return day <= 15 ? (isWeekend ? 139 : 134) : (isWeekend ? 124 : 109)
        case 5:  return day >= 24 ? 134 : (isWeekend ? 124 : 109)
        case 6, 7, 8: return isWeekend ? 139 : 134
        case 9:  return day <= 7 ? 134 : (isWeekend ? 119 : 109)
        case 10: return isWeekend ? 124 : 109
        case 11: return day >= 23 ? 139 : (isWeekend ? 124 : 109)
        case 12: return day >= 21 ? 139 : (isWeekend ? 134 : 119)
        default: return 119
        }
    }

